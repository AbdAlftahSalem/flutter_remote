/**
 * Scaffolding: copies the runner bundle (src/runner) into the user's Flutter
 * repository, and keeps it up to date safely.
 *
 *   src/runner/workflow/flutter-remote.yml  -> .github/workflows/flutter-remote.yml
 *   src/runner/flutter-remote/**            -> .github/flutter-remote/**   (1:1)
 *
 * Every written file starts with a one-line header holding the hash of the
 * body we wrote. On the next run that tells three cases apart without anyone
 * having to remember to bump a version number:
 *   - body still matches its header hash -> ours and untouched -> upgrade it
 *   - body changed since we wrote it     -> the user edited it -> keep it, warn
 *   - an old "template-version: N" header -> written by flutter-remote <= 0.1.x -> upgrade
 * Files we wrote earlier that this version no longer ships are removed, unless
 * the user edited them.
 * Line endings are normalized before hashing, so a Windows checkout with
 * CRLF endings is not mistaken for a user edit.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const RUNNER_SOURCE = join(dirname(fileURLToPath(import.meta.url)), '..', 'runner');
export const WORKFLOW_FILE = 'flutter-remote.yml';
export const WORKFLOW_PATH = `.github/workflows/${WORKFLOW_FILE}`;
export const BUNDLE_DIR = '.github/flutter-remote';
export const GATE_PATH = `${BUNDLE_DIR}/gate.cjs`;
export const WEBRTC_PEER_PATH = `${BUNDLE_DIR}/webrtc-peer.cjs`;

const HEADER_RE = /^(?:\/\/|#) flutter-remote:managed sha256=([0-9a-f]{16})\b.*$/;
const LEGACY_HEADER_RE = /^(?:\/\/|#) flutter-remote-template-version:\s*\d+/;

const normalize = (text) => text.replace(/\r\n/g, '\n');
const hashOf = (body) => createHash('sha256').update(normalize(body)).digest('hex').slice(0, 16);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]);
}

/** Every file the scaffold manages: `{ dest, source }`, dest relative to the app repo. */
export function manifest() {
  const bundleRoot = join(RUNNER_SOURCE, 'flutter-remote');
  return [
    { dest: WORKFLOW_PATH, source: join(RUNNER_SOURCE, 'workflow', 'flutter-remote.yml') },
    ...walk(bundleRoot).sort().map((source) => ({
      dest: `${BUNDLE_DIR}/${relative(bundleRoot, source).split(sep).join('/')}`,
      source,
    })),
  ];
}

/** The exact text written for a template: header line + body. */
export function render(source) {
  const body = normalize(readFileSync(source, 'utf8'));
  const comment = source.endsWith('.yml') ? '#' : '//';
  return `${comment} flutter-remote:managed sha256=${hashOf(body)} — generated by flutter-remote; edits are kept, \`flutter-remote init --force\` restores it\n${body}`;
}

/**
 * Classify an existing file against the template.
 * @returns {'missing'|'current'|'outdated'|'legacy'|'modified'|'foreign'}
 */
export function classify(existingText, renderedText) {
  if (existingText === undefined) return 'missing';
  const existing = normalize(existingText);
  if (existing === renderedText) return 'current';
  const [first, ...rest] = existing.split('\n');
  const managed = HEADER_RE.exec(first);
  if (managed) return hashOf(rest.join('\n')) === managed[1] ? 'outdated' : 'modified';
  if (LEGACY_HEADER_RE.test(first)) return 'legacy';
  return 'foreign';
}

/** Is this file one we wrote and nobody edited since (or a 0.1.x file)? */
function ownedAndUntouched(text) {
  const [first, ...rest] = normalize(text).split('\n');
  const managed = HEADER_RE.exec(first);
  return managed ? hashOf(rest.join('\n')) === managed[1] : LEGACY_HEADER_RE.test(first);
}

/** Files under .github/flutter-remote that we wrote but no longer ship. */
function staleFiles(cwd, shipped) {
  const dir = join(cwd, BUNDLE_DIR);
  if (!existsSync(dir)) return [];
  return walk(dir)
    .map((abs) => `${BUNDLE_DIR}/${relative(dir, abs).split(sep).join('/')}`)
    .filter((dest) => !shipped.has(dest) && ownedAndUntouched(readFileSync(join(cwd, dest), 'utf8')));
}

/**
 * Bring the app repository's flutter-remote files up to date.
 * @returns {{ written: string[], updated: string[], removed: string[], kept: string[], unchanged: string[] }}
 */
export function scaffold(cwd, { force = false } = {}) {
  const report = { written: [], updated: [], removed: [], kept: [], unchanged: [] };
  const files = manifest();
  for (const dest of staleFiles(cwd, new Set(files.map((f) => f.dest)))) {
    rmSync(join(cwd, dest));
    report.removed.push(dest);
  }
  for (const { dest, source } of files) {
    const target = join(cwd, dest);
    const rendered = render(source);
    const state = classify(existsSync(target) ? readFileSync(target, 'utf8') : undefined, rendered);

    if (state === 'current') { report.unchanged.push(dest); continue; }
    if ((state === 'modified' || state === 'foreign') && !force) { report.kept.push(dest); continue; }

    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, rendered);
    (state === 'missing' ? report.written : report.updated).push(dest);
  }
  return report;
}

/** True when the scaffold changed anything on disk. */
export const changed = (report) => report.written.length + report.updated.length + report.removed.length > 0;
